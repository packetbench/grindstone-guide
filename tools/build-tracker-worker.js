"use strict";
// No external build dependencies. The generated ES module can be pasted into
// Cloudflare's Worker editor, with the D1 binding named DB.
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const target = path.join(root, "tracker-api", "bundle.mjs");
function preflight(file) {
  if (file.length > 200) throw new Error("Generated path exceeds the workspace's 200-unit target.");
  const relative = path.relative(root, file);
  for (const [index, part] of relative.split(path.sep).entries()) {
    const isFile = index === relative.split(path.sep).length - 1;
    if (part.length > (isFile ? 64 : 32) || !/^[a-z0-9_-]+(?:\.[a-z0-9_-]+)*$/.test(part) || /^(con|prn|aux|nul|com[0-9]|lpt[0-9])(?:\.|$)/i.test(part) || part === "_vti_") throw new Error("Unsafe generated path component: " + part);
  }
  const sibling = fs.readdirSync(path.dirname(file)).find(name => name.toLowerCase() === path.basename(file).toLowerCase() && name !== path.basename(file));
  if (sibling) throw new Error("Case-insensitive output collision: " + sibling);
}
preflight(target);
const model = fs.readFileSync(path.join(root, "tracker-model.js"), "utf8");
const worker = fs.readFileSync(path.join(root, "tracker-api", "worker.mjs"), "utf8").replace(/^import "\.\.\/tracker-model\.js";\r?\n/m, "");
if (/^import /m.test(worker)) throw new Error("Unexpected Worker import: update the dependency-free bundler.");
fs.writeFileSync(target, "// Generated by tools/build-tracker-worker.js; edit source files instead.\n" + model + "\n" + worker, "utf8");
console.log("Built tracker-api/bundle.mjs");
